import React from 'react';
import {act,create} from 'react-test-renderer';
import assert from 'node:assert/strict';
import {WebsitePublishPanel} from '../src/components/WebsitePublishPanel';
import {CATEGORY_TEMPLATES} from '../src/categoryTemplates';
import {INITIAL_SALON_PROFILE} from '../src/mockData';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT=true;
(globalThis as any).location={origin:'https://studioflow.example'};
let copied='';Object.defineProperty(globalThis,'navigator',{configurable:true,value:{clipboard:{writeText:async(value:string)=>{copied=value;}}}});
const readyProfile={...INITIAL_SALON_PROFILE,businessName:'Roop Mahal Beauty Parlour',serviceCatalogueInitialized:true};
const readyServices=CATEGORY_TEMPLATES.beauty_parlour.services;
let root:any,calls=0,success=0,release:()=>void=()=>{};
const pending=new Promise<void>(resolve=>{release=resolve;});
await act(async()=>{root=create(<WebsitePublishPanel published={null} onPublish={async()=>{calls++;await pending;}} onPublished={()=>success++} profile={readyProfile} services={readyServices}/>);});
assert.equal(root.root.findAllByType('a').length,0,'Draft must not show a live URL');
assert.equal(root.root.findByType('button').props.disabled,false,'Ready workspace must enable publish');
await act(async()=>{root.root.findByType('button').props.onClick();root.root.findByType('button').props.onClick();});
assert.equal(calls,1);
assert.equal(root.root.findByType('button').props.disabled,true);
await act(async()=>release());assert.equal(success,1);
await act(async()=>root.update(<WebsitePublishPanel published={{slug:'my-salon',published_at:'2026-10-11'}} profile={readyProfile} services={readyServices}/>));
assert.equal(root.root.findAllByType('a')[1].props.href,'https://studioflow.example/?site=my-salon');
await act(async()=>root.root.findByType('button').props.onClick());
assert.equal(copied,'https://studioflow.example/?site=my-salon');
await act(async()=>root.unmount());
await act(async()=>{root=create(<WebsitePublishPanel published={null} onPublish={async()=>{calls++;}} profile={{...INITIAL_SALON_PROFILE,businessName:'Unready Salon',serviceCatalogueInitialized:false}} services={[]}/>);});
assert.equal(root.root.findByType('button').props.disabled,true,'Publishing checklist must gate an unready workspace');
await act(async()=>root.root.findByType('button').props.onClick());
assert.equal(calls,1,'Unready workspace must not call onPublish');
await act(async()=>root.unmount());
await act(async()=>{root=create(<WebsitePublishPanel published={null} onPublish={async()=>{throw new Error('Save failed');}} onPublished={()=>success++} profile={readyProfile} services={readyServices}/>);});
await act(async()=>root.root.findByType('button').props.onClick());
assert.equal(success,1);
assert.deepEqual(root.root.findByProps({role:'alert'}).children,['Save failed']);
await act(async()=>root.unmount());
console.log('PASS: draft hides URL; readiness checklist gates publish; publish prevents duplicates; success callback; live URL and clipboard; persistent error without false success.');
