import React from 'react';
import {act,create} from 'react-test-renderer';
import assert from 'node:assert/strict';
import {WebsitePublishPanel} from '../src/components/WebsitePublishPanel';
import {formatPublishingError} from '../src/lib/publishing';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT=true;
(globalThis as any).location={origin:'https://studioflow.example'};
let copied='';Object.defineProperty(globalThis,'navigator',{configurable:true,value:{clipboard:{writeText:async(value:string)=>{copied=value;}}}});
let root:any,calls=0,success=0,release:()=>void=()=>{};
const pending=new Promise<void>(resolve=>{release=resolve;});
const profile={businessName:'Salon',serviceCatalogueInitialized:true} as any;
const services=[{id:'service',name:'Cut'}] as any;
await act(async()=>{root=create(<WebsitePublishPanel published={null} profile={profile} services={services} onPublish={async()=>{calls++;await pending;}} onPublished={()=>success++}/>);});
assert.equal(root.root.findAllByType('a').length,0,'Draft must not show a live URL');
await act(async()=>{root.root.findByType('button').props.onClick();root.root.findByType('button').props.onClick();});
assert.equal(calls,1);assert.equal(root.root.findByType('button').props.disabled,true);
assert.equal(root.root.findAllByProps({role:'status'}).length,0,'Publish success is not shown before the RPC completes');
await act(async()=>release());assert.equal(success,1);
await act(async()=>root.update(<WebsitePublishPanel published={{slug:'my-salon',published_at:'2026-10-11'}}/>));
assert.equal(root.root.findAllByType('a')[1].props.href,'https://studioflow.example/?site=my-salon');
await act(async()=>root.root.findByType('button').props.onClick());assert.equal(copied,'https://studioflow.example/?site=my-salon');
await act(async()=>root.unmount());
const successBeforeFailure=success;
await act(async()=>{root=create(<WebsitePublishPanel published={null} profile={profile} services={services} onPublish={async()=>{throw {message:'duplicate key value violates unique constraint',code:'23505',details:'Key (slug) already exists',hint:'Choose another website address'};}} onPublished={()=>success++}/>);});
await act(async()=>root.root.findByType('button').props.onClick());
assert.equal(success,successBeforeFailure,'Failed publish must not call the success callback');
assert.deepEqual(root.root.findByProps({role:'alert'}).children,['duplicate key value violates unique constraint · Details: Key (slug) already exists · Hint: Choose another website address · Code: 23505']);
await act(async()=>root.unmount());
assert.equal(formatPublishingError({message:'row-level security policy violation',code:'42501'}),'row-level security policy violation · Code: 42501');
assert.equal(formatPublishingError(new Error('Sign in required')),'Sign in required');
console.log('PASS: draft hides URL; publish prevents duplicates; success callback; live URL and clipboard; persistent error without false success.');
