import React from 'react';
import { act, create } from 'react-test-renderer';
import assert from 'node:assert/strict';
(globalThis as any).IS_REACT_ACT_ENVIRONMENT = true;
const storage = new Map();
(globalThis as any).localStorage = { getItem: (k:string) => storage.get(k) ?? null, setItem: (k:string,v:string) => storage.set(k,v), removeItem: (k:string) => storage.delete(k) };
(globalThis as any).sessionStorage = localStorage;
let navigated = '';
(globalThis as any).location = { origin: 'https://salon.example', search: '', hash: '', assign: (url:string) => { navigated = url; } };
const { AuthPage } = await import('../src/components/AuthPage');
const { supabase } = await import('../src/lib/supabase');
let resetRequest:any, updates=0, signouts=0;
supabase.auth.resetPasswordForEmail = async (email,options) => { resetRequest={email,options}; return {data:{},error:null}; };
supabase.auth.updateUser = (async () => { updates++; return {data:{user:{}},error:null}; }) as any;
supabase.auth.signOut = async () => { signouts++; return {error:null}; };
let view:any;
await act(async()=> { view=create(<AuthPage customerMode returnSlug="my-salon"/>); });
const button=(text:string)=>view.root.findAllByType('button').find((b:any)=>b.children.join('')===text);
await act(async()=>button('Forgot password?').props.onClick());
assert.equal(view.root.findAllByType('input').length,1,'Forgot password asks only for email');
await act(async()=>view.root.findByType('input').props.onChange({target:{value:' client@example.com '}}));
await act(async()=>view.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.deepEqual(resetRequest,{email:'client@example.com',options:{redirectTo:'https://salon.example/?customer=1&return=my-salon&recovery=1'}});
assert.equal(button('Reset link requested — check email').props.disabled,true);
assert.match(view.root.findByProps({role:'status'}).children.join(''),/If an account exists/);
await act(async()=>button('Back to sign in').props.onClick());
assert.ok(button('Forgot password?'));
await act(async()=>view.unmount());
await act(async()=> { view=create(<AuthPage recovery customerMode returnSlug="my-salon"/>); });
const inputs=view.root.findAllByType('input');
await act(async()=>{inputs[0].props.onChange({target:{value:'NewPassword123!'}});inputs[1].props.onChange({target:{value:'Mismatch123!'}});});
await act(async()=>view.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.equal(updates,0,'Mismatched passwords must not reach Supabase');
await act(async()=>inputs[1].props.onChange({target:{value:'NewPassword123!'}}));
await act(async()=>view.root.findByType('form').props.onSubmit({preventDefault(){}}));
assert.equal(updates,1);assert.equal(signouts,1);assert.equal(navigated,'/?customer=1&return=my-salon&passwordUpdated=1');
await act(async()=>view.unmount());
console.log('PASS: forgot-password entry, reset request and customer redirect, email notice, duplicate prevention, password confirmation and successful reset handoff. Supabase calls mocked; email delivery requires configured SMTP.');
