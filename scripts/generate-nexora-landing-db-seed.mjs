/**
 * Generates the NEXORA SALONOS landing-page seed migration from the content
 * that is actually published on the site.
 *
 * The seed is intentionally conservative:
 *   * only copy that is already live on nexorasalon.online/salon-os is written;
 *   * prices are the approved annual totals (monthly stays NULL — no invented
 *     price, no invented discount);
 *   * only the three explicitly confirmed Standard entitlements get a
 *     plan_features row — every unconfirmed tier assignment stays absent;
 *   * promotional creatives are seeded as DRAFTS because the image objects do
 *     not exist in the bucket yet;
 *   * testimonials are never seeded — no approved customer quote exists.
 *
 * Run: node scripts/generate-nexora-landing-db-seed.mjs
 */
import { writeFileSync } from 'node:fs';
import { build } from 'esbuild';

const load = async (entry) => {
  const bundled = await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', write: false });
  const dataUrl = `data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`;
  return import(dataUrl);
};

// The landing content module re-uses the approved pricing catalogue, so both
// modules are loaded and merged into one read-only view of the real content.
const content = { ...(await load('src/lib/nexoraPricing.ts')), ...(await load('src/lib/nexoraLandingContent.ts')) };

const q = (value) => {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replace(/'/g, "''")}'`;
};
const j = (value) => `${q(JSON.stringify(value))}::jsonb`;
const n = (value) => (value === null || value === undefined ? 'null' : String(value));
const row = (values) => `  (${values.join(', ')})`;

const sql = [];
const push = (line = '') => sql.push(line);

/* --------------------------------------------------------------------------
 * Guard rails: the seed must never invent commercial data.
 * ------------------------------------------------------------------------ */
const catalogue = content.FEATURE_CATEGORIES.flatMap((category) =>
  category.items.map((item) => ({ ...item, catalogueCategory: category.id })),
);
const comparisonFeatures = content.NEXORA_LANDING_COMPARISON_GROUPS.flatMap((group) =>
  group.featureIds.map((id) => ({ id, group: group.id })),
);
const comparisonIds = comparisonFeatures.map((entry) => entry.id);
if (new Set(comparisonIds).size !== comparisonIds.length) {
  throw new Error('A feature is listed in more than one comparison group.');
}
const missingFromComparison = catalogue.filter((item) => !comparisonIds.includes(item.id));
if (missingFromComparison.length) {
  throw new Error(`Catalogue features missing from the comparison groups: ${missingFromComparison.map((i) => i.id).join(', ')}`);
}
const unknownFeatures = comparisonIds.filter((id) => !catalogue.some((item) => item.id === id));
if (unknownFeatures.length) {
  throw new Error(`Comparison groups reference unknown features: ${unknownFeatures.join(', ')}`);
}

const confirmedEntitlements = Object.entries(content.FEATURE_PLAN_ENTITLEMENTS).filter(
  ([, plans]) => plans.standard === 'included',
);
if (confirmedEntitlements.length !== 3) {
  throw new Error('Expected exactly three approved Standard entitlements.');
}

